-- Languages (2026-11-24, Londi: English, Spanish and French for the app and everything anlim makes). @anlim
-- The creator's language lives on the account, so the "ready" emails, the end card on cuts and anlim's notices follow it
-- on every device. null = not chosen yet (the app sends the device's language on first sign-in).
alter table studio.accounts add column if not exists language text
  check (language is null or language in ('en', 'es', 'fr'));

create or replace function studio.set_language(p_language text) returns void language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then raise exception 'sign in first'; end if;
  if p_language is null or p_language not in ('en', 'es', 'fr') then raise exception 'language must be en, es or fr'; end if;
  insert into studio.accounts(owner) values (auth.uid()) on conflict do nothing;
  update studio.accounts set language = p_language, updated_at = now() where owner = auth.uid();
end $$;
revoke execute on function studio.set_language(text) from public, anon;
grant execute on function studio.set_language(text) to authenticated;

-- Text anlim writes at run time (errors, check findings, cut notes, notices) is written in English. For a creator who chose
-- Spanish or French it is shown through this table: studio-api looks a message up and, when it is not there yet, adds
-- it without a translation; the worker fills the empty ones in batches (Claude, through the checker's /translate) and
-- later requests show the translation. Numbers are taken out first (⟨0⟩, ⟨1⟩...) so "Shot 3: trimmed to 2.10 s" and
-- "Shot 5: trimmed to 1.00 s" share one row. lang 'en' holds the other direction: a creator's Spanish or French shot
-- text put into English for the image and video models, which follow English best.
create table if not exists studio.translations (
  src        text not null,
  lang       text not null check (lang in ('en', 'es', 'fr')),
  out        text,
  tries      int not null default 0,
  created_at timestamptz not null default now(),
  done_at    timestamptz,
  primary key (lang, src)
);
alter table studio.translations enable row level security;   -- service role only (studio-api, worker); no policies
create index if not exists translations_todo on studio.translations (created_at) where out is null;
grant select, insert, update on studio.translations to studio_worker;
drop policy if exists translations_worker on studio.translations;
create policy translations_worker on studio.translations for all to studio_worker using (true) with check (true);

